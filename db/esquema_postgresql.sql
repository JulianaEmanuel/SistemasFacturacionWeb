-- Funciones de compatibilidad para consultas de la aplicación (SQL Server -> PostgreSQL)
CREATE OR REPLACE FUNCTION dbo.col_length(tbl text, col text)
RETURNS integer LANGUAGE plpgsql AS $$
DECLARE
    v_tbl text := lower(split_part(tbl, '.', 2));
    v_col text := lower(col);
BEGIN
    IF v_tbl = '' THEN v_tbl := lower(tbl); END IF;
    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'dbo'
          AND lower(table_name) = v_tbl
          AND lower(column_name) = v_col
    ) THEN
        RETURN 1;
    ELSE
        RETURN NULL;
    END IF;
END;
$$;

CREATE OR REPLACE FUNCTION dbo.object_id(tbl text, typ text DEFAULT 'U')
RETURNS integer LANGUAGE plpgsql AS $$
DECLARE
    v_tbl text := lower(split_part(tbl, '.', 2));
BEGIN
    IF v_tbl = '' THEN v_tbl := lower(tbl); END IF;
    IF EXISTS (
        SELECT 1 FROM information_schema.tables
        WHERE table_schema = 'dbo'
          AND lower(table_name) = v_tbl
    ) THEN
        RETURN 1;
    ELSE
        RETURN NULL;
    END IF;
END;
$$;

CREATE OR REPLACE FUNCTION dbo.count_big_star_sfunc(bigint) RETURNS bigint
LANGUAGE sql IMMUTABLE AS 'SELECT $1 + 1';

CREATE OR REPLACE AGGREGATE dbo.count_big(*) (
    SFUNC = dbo.count_big_star_sfunc,
    STYPE = bigint,
    INITCOND = '0'
);

CREATE OR REPLACE AGGREGATE dbo.count_big(anyelement) (
    SFUNC = int8inc_any,
    STYPE = int8,
    INITCOND = '0'
);

