        REFERENCES dbo.TipoUsuario (ID_TIPO_USUARIO),
    CONSTRAINT CK_Usuario_CorreoVerificado CHECK (CORREO_USUARIO IS NOT NULL OR CORREO_VERIFICADO_EN IS NULL)
);

CREATE UNIQUE INDEX IF NOT EXISTS UX_Usuario_CorreoVerificado
    ON dbo.Usuario (CORREO_USUARIO)
    WHERE CORREO_USUARIO IS NOT NULL AND CORREO_VERIFICADO_EN IS NOT NULL;

