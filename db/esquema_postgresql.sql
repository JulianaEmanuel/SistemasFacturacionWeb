CREATE TABLE IF NOT EXISTS dbo.FacturaPago (
    ID_FACTURA_PAGO BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_FACTURA BIGINT NOT NULL CONSTRAINT UQ_FacturaPago_Factura UNIQUE,
    ID_FORMA_PAGO INT NOT NULL,
    NOMBRE_FORMA_PAGO VARCHAR(80) NOT NULL,
    IMPORTE NUMERIC(18, 4) NOT NULL CONSTRAINT CK_FacturaPago_Importe CHECK (IMPORTE >= 0),
    MONTO_RECIBIDO NUMERIC(18, 4) NULL CONSTRAINT CK_FacturaPago_MontoRecibido CHECK (MONTO_RECIBIDO >= 0),
    CAMBIO NUMERIC(18, 4) NULL CONSTRAINT CK_FacturaPago_Cambio CHECK (CAMBIO >= 0),
    BANCO VARCHAR(80) NULL,
    REFERENCIA VARCHAR(30) NULL,
    MARCA_TARJETA VARCHAR(30) NULL,
    ULTIMOS_DIGITOS VARCHAR(4) NULL CONSTRAINT CK_FacturaPago_UltimosDigitos CHECK (ULTIMOS_DIGITOS ~ '^[0-9]{4}$'),
    CUOTAS SMALLINT NULL CONSTRAINT CK_FacturaPago_Cuotas CHECK (CUOTAS BETWEEN 1 AND 48),
    CONSTRAINT FK_FacturaPago_Factura FOREIGN KEY (ID_FACTURA)
        REFERENCES dbo.Factura (ID_FACTURA),
    CONSTRAINT FK_FacturaPago_FormaPago FOREIGN KEY (ID_FORMA_PAGO)
        REFERENCES dbo.FormaPago (ID_FORMA_PAGO)
);

