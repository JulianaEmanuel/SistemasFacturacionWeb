    ID_USUARIO BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_TIPO_USUARIO INT NOT NULL,
    NOMBRE_USUARIO VARCHAR(100) NOT NULL,
